    private void actualizarHorasDisponibles() {
        
    if (!(jSpinnerFecha.getValue() instanceof Date)) return;
    if (jComboBox5.getSelectedIndex() == 0 || jSpinnerFecha.getValue() == null) return;

    int idPista = Integer.parseInt(jComboBox5.getSelectedItem().toString().split(" - ")[0]);
    Date fechaSeleccionada = (Date) jSpinnerFecha.getValue();
    LocalDate fecha = fechaSeleccionada.toInstant()
            .atZone(ZoneId.systemDefault())
            .toLocalDate();

    acceso.AccesoPadelProject acceso = new acceso.AccesoPadelProject();
    Map disponibilidad = acceso.obtenerObjeto(
        "/pistas/" + idPista + "/disponibilidad?fecha=" + fecha, Map.class);

    if (disponibilidad == null) return;

    List<String> horasLibres = (List<String>) disponibilidad.get("horasLibres");
    if (horasLibres == null || horasLibres.isEmpty()) return;

    // Extraer horas inicio únicas (parte izquierda de "08:00 - 09:00")
    Set<String> inicios = new LinkedHashSet<>();
    Set<String> fines = new LinkedHashSet<>();
    
    for (String tramo : horasLibres) {
        String[] partes = tramo.split(" - ");
        inicios.add(partes[0]); // "08:00"
        fines.add(partes[1]);   // "09:00"
    }

    // Actualizar combobox hora inicio
    jComboBox2.removeAllItems();
    jComboBox2.addItem("-Selecciona hora inicio-");
    for (String h : inicios) {
        jComboBox2.addItem(h);
    }

    // Actualizar combobox hora fin
    jComboBox1.removeAllItems();
    jComboBox1.addItem("-Seleccione hora fin-");
    for (String h : fines) {
        jComboBox1.addItem(h);
    }
}

