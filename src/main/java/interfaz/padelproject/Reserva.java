    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        if (jComboBox2.getSelectedIndex() == 0 || jComboBox1.getSelectedIndex() == 0
                || jComboBox3.getSelectedIndex() == 0
                || jComboBox4.getSelectedIndex() == 0
                || jComboBox5.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Rellena todos los campos");
            return;
        }

        int idUsuario = Integer.parseInt(jComboBox4.getSelectedItem().toString().split(" - ")[0]);
        int idPista = Integer.parseInt(jComboBox5.getSelectedItem().toString().split(" - ")[0]);

        Map<String, Object> usuario = new HashMap<>();
        usuario.put("id", idUsuario);

        Map<String, Object> pista = new HashMap<>();
        pista.put("id", idPista);

        Date fechaSeleccionada = (Date) jSpinnerFecha.getValue();
        LocalDate fecha = fechaSeleccionada.toInstant()
                .atZone(ZoneId.systemDefault())
                .toLocalDate();

        if (fecha.isBefore(LocalDate.now())) {
            JOptionPane.showMessageDialog(this, "No puedes crear una reserva en una fecha pasada");
            return;
        }
        int hInicio = Integer.parseInt(jComboBox2.getSelectedItem().toString().split(":")[0]);
        int hFin = Integer.parseInt(jComboBox1.getSelectedItem().toString().split(":")[0]);
        String horaInicioCompleta = fecha + "T" + String.format("%02d", hInicio) + ":00:00";
        String horaFinCompleta = fecha + "T" + String.format("%02d", hFin) + ":00:00";

        Map<String, Object> reserva = new HashMap<>();
        reserva.put("usuario", usuario);
        reserva.put("pista", pista);
        reserva.put("horaInicio", horaInicioCompleta);
        reserva.put("horaFin", horaFinCompleta);
        reserva.put("estado", jComboBox3.getSelectedItem().toString().trim());
        reserva.put("precioTotal", Double.parseDouble(jTextField2.getText()));

        acceso.AccesoPadelProject acceso = new acceso.AccesoPadelProject();
        boolean creado = acceso.crear("/reservas", reserva);

         
        if (creado) {
            JOptionPane.showMessageDialog(this, "Reserva creada correctamente");
            jComboBox1.setSelectedIndex(0);
            jComboBox2.setSelectedIndex(0);
            jComboBox3.setSelectedIndex(0);
            jComboBox4.setSelectedIndex(0);
            jComboBox5.setSelectedIndex(0);
            jTextField2.setText("");
        } else {
            JOptionPane.showMessageDialog(this, "Error al crear la reserva, tramo horario/pista no disponible");
        }

       this.dispose();
    }//GEN-LAST:event_jButton1ActionPerformed

