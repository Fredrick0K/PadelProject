    private void cargarUsuarios() {
        acceso.AccesoPadelProject acceso = new acceso.AccesoPadelProject();
        List<Map> usuarios = acceso.obtenerLista("/usuarios", Map.class);

        jComboBox4.removeAllItems();
        jComboBox4.addItem("-Selecciona usuario-");

        for (Map u : usuarios) {
            jComboBox4.addItem(u.get("id") + " - " + u.get("nombre"));
        }
    }

    private void cargarPistas() {
        acceso.AccesoPadelProject acceso = new acceso.AccesoPadelProject();
        List<Map> pistas = acceso.obtenerLista("/pistas", Map.class);

        jComboBox5.removeAllItems();
        jComboBox5.addItem("-Selecciona pista-");

        for (Map p : pistas) {
            int id = (int) p.get("id");
            double precio = (double) p.get("precioHora");
            preciosPistas.put(id, precio); // guarda el precio
            jComboBox5.addItem(id + " - " + p.get("nombre"));
        }
    }

    private void calcularPrecio() {
        if (jComboBox2.getSelectedIndex() == 0 || jComboBox1.getSelectedIndex() == 0
                || jComboBox5.getSelectedIndex() == 0) {
            jTextField2.setText("");
            return;
        }

        int horaInicio = Integer.parseInt(jComboBox2.getSelectedItem().toString().split(":")[0]);
        int horaFin = Integer.parseInt(jComboBox1.getSelectedItem().toString().split(":")[0]);
        int horas = horaFin - horaInicio;

        if (horas <= 0) {
            jTextField2.setText("Hora inválida");
            return;
        }

        // Obtener precio de la pista seleccionada
        int idPista = Integer.parseInt(jComboBox5.getSelectedItem().toString().split(" - ")[0]);
        double precioPorHora = preciosPistas.getOrDefault(idPista, 0.0);
        double total = horas * precioPorHora;

        jTextField2.setText(String.valueOf(total));
    }

    private void cargarDatosReserva(int id) {
        AccesoPadelProject acceso = new AccesoPadelProject();
        Map reserva = acceso.obtenerObjeto("/reservas/" + id, Map.class);

        if (reserva == null) {
            return;
        }

        jTextField1.setText(reserva.get("id").toString());

        // Cargar estado
        String estado = reserva.get("estado").toString();
        for (int i = 0; i < jComboBox3.getItemCount(); i++) {
            if (jComboBox3.getItemAt(i).trim().equals(estado.trim())) {
                jComboBox3.setSelectedIndex(i);
                break;
            }
        }

        // Cargar usuario
        Map usuario = (Map) reserva.get("usuario");
        int idUsuario = (int) usuario.get("id");
        for (int i = 0; i < jComboBox4.getItemCount(); i++) {
            if (jComboBox4.getItemAt(i).toString().startsWith(idUsuario + " - ")) {
                jComboBox4.setSelectedIndex(i);
                break;
            }
        }

        // Cargar pista
        Map pista = (Map) reserva.get("pista");
        int idPista = (int) pista.get("id");
        for (int i = 0; i < jComboBox5.getItemCount(); i++) {
            if (jComboBox5.getItemAt(i).toString().startsWith(idPista + " - ")) {
                jComboBox5.setSelectedIndex(i);
                break;
            }
        }

        // Cargar horas
        String horaInicio = reserva.get("horaInicio").toString().split("T")[1].substring(0, 5);
        String horaFin = reserva.get("horaFin").toString().split("T")[1].substring(0, 5);

        for (int i = 0; i < jComboBox2.getItemCount(); i++) {
            if (jComboBox2.getItemAt(i).toString().equals(horaInicio)) {
                jComboBox2.setSelectedIndex(i);
                break;
            }
        }
        for (int i = 0; i < jComboBox1.getItemCount(); i++) {
            if (jComboBox1.getItemAt(i).toString().equals(horaFin)) {
                jComboBox1.setSelectedIndex(i);
                break;
            }
        }
        jTextField2.setText(reserva.get("precioTotal").toString());
    }

