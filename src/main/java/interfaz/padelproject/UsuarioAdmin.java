    private void cargarPistas() {
        AccesoPadelProject acceso = new AccesoPadelProject();
        List<Map> pistas = acceso.obtenerLista("/pistas", Map.class);

        DefaultTableModel modelo = (DefaultTableModel) tablePistas.getModel();
        modelo.setRowCount(0);

        for (Map p : pistas) {
            modelo.addRow(new Object[] {
                    p.get("id"),
                    p.get("numeroPista"),
                    p.get("nombre"),
                    p.get("estado"),
                    p.get("precioHora"),
                    p.get("fechaCreacion")
            });
        }
    }

    private void cargarReserva() {
        AccesoPadelProject acceso = new AccesoPadelProject();
        List<Map> reserva = acceso.obtenerLista("/reservas", Map.class);

        DefaultTableModel modelo = (DefaultTableModel) tableReservas.getModel();
        modelo.setRowCount(0);

        for (Map r : reserva) {
            Map usuario = (Map) r.get("usuario");
            Map pista = (Map) r.get("pista");
            modelo.addRow(new Object[] {
                    r.get("id"),
                    usuario.get("id"),
                    pista.get("id"),
                    r.get("horaInicio"),
                    r.get("horaFin"),
                    r.get("estado"),
                    r.get("precioTotal"),
                    r.get("fechaCreacion")
            });
        }
    }

    private void cargarUsuario() {
        AccesoPadelProject acceso = new AccesoPadelProject();
        List<Map> usuario = acceso.obtenerLista("/usuarios", Map.class);

        DefaultTableModel modelo = (DefaultTableModel) tableUsuarios.getModel();
        modelo.setRowCount(0);

        for (Map u : usuario) {
            modelo.addRow(new Object[] {
                    u.get("id"),
                    u.get("nombre"),
                    u.get("email"),
                    u.get("telefono"),
                    u.get("contrasena"),
                    u.get("rol"),
                    u.get("activo"),
                    u.get("fechaCreacion")
            });
        }
    }

