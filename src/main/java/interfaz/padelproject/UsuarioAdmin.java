    private void btnEliminarPistaActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnEliminarPistaActionPerformed
        // TODO add your handling code here:

        int filaSeleccionada = tablePistas.getSelectedRow();

        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona una pista primero");
            return;
        }

        Object id = tablePistas.getValueAt(filaSeleccionada, 0);

        int confirmacion = JOptionPane.showConfirmDialog(this,
                "¿Seguro que quieres eliminar la pista " + id + "?",
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION);

        if (confirmacion == JOptionPane.YES_OPTION) {
            AccesoPadelProject acceso = new AccesoPadelProject();
            boolean eliminado = acceso.eliminar("/pistas/" + id);

            if (eliminado) {
                JOptionPane.showMessageDialog(this, "Pista eliminada correctamente");
                cargarPistas();
            } else {
                JOptionPane.showMessageDialog(this, "Error al eliminar la pista");
            }
        }

    }// GEN-LAST:event_btnEliminarPistaActionPerformed

