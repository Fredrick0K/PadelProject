    private void cargarMisReservas() {
        int idUsuario = AccesoPadelProject.getIdUsuario();

        acceso.AccesoPadelProject acceso = new acceso.AccesoPadelProject();
        java.util.List<Map> reservas = acceso.obtenerLista(
                "/reservas/usuario/" + idUsuario, Map.class);

        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0);

        for (Map r : reservas) {
            Map usuario = (Map) r.get("usuario");
            Map pista = (Map) r.get("pista");

            modelo.addRow(new Object[] {
                    r.get("id"),
                    usuario.get("id"),
                    pista.get("id"),
                    r.get("horaInicio"),
                    r.get("horaFin"),
                    r.get("estado"),
                    r.get("precioTotal"),
                    r.get("fechaCreacion")
            });
        }
    }

