    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        int filaSeleccionada = jTable1.getSelectedRow();

        if (filaSeleccionada == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecciona una reserva primero");
            return;
        }

        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this,
                "¿Seguro que quieres cancelar esta reserva?",
                "Confirmar cancelación",
                javax.swing.JOptionPane.YES_NO_OPTION);

        if (confirmacion != JOptionPane.YES_OPTION)
            return;

        Object id = jTable1.getValueAt(filaSeleccionada, 0);

        // Obtener la reserva original para no perder datos
        AccesoPadelProject acceso = new acceso.AccesoPadelProject();
        Map reservaOriginal = acceso.obtenerObjeto("/reservas/" + id, java.util.Map.class);

        if (reservaOriginal == null) {
            JOptionPane.showMessageDialog(this, "Error al obtener la reserva");
            return;
        }

        // Modificar solo el estado
        java.util.Map<String, Object> reserva = new java.util.HashMap<>();
        reserva.put("id", id);
        reserva.put("usuario", reservaOriginal.get("usuario"));
        reserva.put("pista", reservaOriginal.get("pista"));
        reserva.put("horaInicio", reservaOriginal.get("horaInicio"));
        reserva.put("horaFin", reservaOriginal.get("horaFin"));
        reserva.put("estado", "CANCELADA");
        reserva.put("precioTotal", reservaOriginal.get("precioTotal"));
        reserva.put("fechaCreacion", reservaOriginal.get("fechaCreacion"));

        boolean cancelado = acceso.crear("/reservas", reserva);

        if (cancelado) {
            javax.swing.JOptionPane.showMessageDialog(this, "Reserva cancelada correctamente");
            cargarMisReservas(); // recarga la tabla
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al cancelar la reserva");
        }

    }// GEN-LAST:event_jButton1ActionPerformed

