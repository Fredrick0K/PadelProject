private void cargarDatosUsuario(int id) {
        acceso.AccesoPadelProject acceso = new acceso.AccesoPadelProject();
        Map usuario = acceso.obtenerObjeto("/usuarios/" + id, Map.class);

        if (usuario == null) {
            return;
        }

        // Identificador
        jTextField5.setText(usuario.get("id").toString());

        // Nombre
        jTextField1.setText(usuario.get("nombre").toString());

        // Email
        jTextField2.setText(usuario.get("email").toString());

        // Teléfono
        jTextField3.setText(usuario.get("telefono").toString());

        // Contraseña
        jTextField4.setText(usuario.get("contrasena").toString());

        // Rol
        String rol = usuario.get("rol").toString();
        for (int i = 0; i < jComboBox1.getItemCount(); i++) {
            if (jComboBox1.getItemAt(i).equals(rol)) {
                jComboBox1.setSelectedIndex(i);
                break;
            }
        }

        // Activo
        jCheckBox1.setSelected((boolean) usuario.get("activo"));
    }

