    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:

        if (jTextField1.getText().isEmpty() || jTextField2.getText().isEmpty()
                || jTextField3.getText().isEmpty() || jTextField4.getText().isEmpty()
                || jComboBox1.getSelectedIndex() == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Rellena todos los campos");
            return;
        }

        Map<String, Object> usuario = new HashMap<>();
        usuario.put("nombre", jTextField1.getText());
        usuario.put("email", jTextField2.getText());
        usuario.put("telefono", jTextField3.getText());
        usuario.put("contrasena", jTextField4.getText());
        usuario.put("rol", jComboBox1.getSelectedItem().toString());
        usuario.put("activo", jCheckBox1.isSelected());

        acceso.AccesoPadelProject acceso = new acceso.AccesoPadelProject();
        boolean creado = acceso.crear("/usuarios", usuario);

        if (creado) {
            javax.swing.JOptionPane.showMessageDialog(this, "Usuario creado correctamente");
            jTextField1.setText("");
            jTextField2.setText("");
            jTextField3.setText("");
            jTextField4.setText("");
            jTextField5.setText("");
            jComboBox1.setSelectedIndex(0);
            jCheckBox1.setSelected(false);
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al crear el usuario");
        }

    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        if (idUsuario == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "No hay usuario seleccionado");
            return;
        }

        Map<String, Object> usuario = new HashMap<>();
        usuario.put("id", idUsuario);
        usuario.put("nombre", jTextField1.getText());
        usuario.put("email", jTextField2.getText());
        usuario.put("telefono", jTextField3.getText());
        usuario.put("contrasena", jTextField4.getText());
        usuario.put("rol", jComboBox1.getSelectedItem().toString());
        usuario.put("activo", jCheckBox1.isSelected());
        usuario.put("fechaCreacion", LocalDateTime.now());

        AccesoPadelProject acceso = new AccesoPadelProject();
        boolean modificado = acceso.modificar("/usuarios/" + idUsuario, usuario);

        if (modificado) {
            JOptionPane.showMessageDialog(this, "Usuario modificado correctamente");
            dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Error al modificar el usuario");
        }

    }//GEN-LAST:event_jButton2ActionPerformed

